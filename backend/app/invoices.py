from __future__ import annotations

from pathlib import Path
from textwrap import wrap

try:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.pdfgen import canvas
    REPORTLAB_AVAILABLE = True
except Exception:  # pragma: no cover - fallback when reportlab is unavailable
    REPORTLAB_AVAILABLE = False


def _sanitize(value: str) -> str:
    replacements = {
        '•': '-',
        '—': '-',
        '–': '-',
        '“': '"',
        '”': '"',
        '’': "'",
        '₹': 'Rs ',
    }
    clean = str(value or '')
    for old, new in replacements.items():
        clean = clean.replace(old, new)
    return clean.encode('latin-1', 'replace').decode('latin-1')


def _escape_pdf_text(value: str) -> str:
    clean = _sanitize(value).replace('\\', '\\\\').replace('(', '\\(').replace(')', '\\)')
    return clean


def _line_chunks(label: str, width: int = 74) -> list[str]:
    text = _sanitize(label)
    return wrap(text, width=width) or ['']


def _item_label(item: dict) -> str:
    parts = [str(item.get('model') or '').strip()]
    for key in ('company', 'color', 'size'):
        value = str(item.get(key) or '').strip()
        if value:
            parts.append(value)
    return ' | '.join([part for part in parts if part])


def _invoice_lines(invoice: dict, items: list[dict], shop_name: str) -> list[str]:
    lines = [
        shop_name,
        'Sales Invoice',
        f"Invoice #: {invoice['invoice_number']}",
        f"Date: {invoice['invoice_date']}",
        f"Customer: {invoice['customer_name']}",
        f"Phone: {invoice.get('phone_number') or '-'}",
        f"Address: {invoice.get('address') or '-'}",
        f"Status: {invoice['status']}",
        '',
        'Items',
        '--------------------------------------------------------------',
    ]

    for item in items:
        total_price = float(item.get('total_price') or 0)
        qty = int(float(item.get('quantity') or 0))
        unit_price = float(item.get('unit_price') or 0)
        label = _item_label(item)
        for chunk in _line_chunks(label):
            lines.append(chunk)
        lines.append(f"Qty {qty}   Rate Rs {unit_price:,.2f}   Total Rs {total_price:,.2f}")
        lines.append('')

    lines.extend([
        '--------------------------------------------------------------',
        f"Subtotal: Rs {float(invoice.get('subtotal') or 0):,.2f}",
    ])
    discount_amount = float(invoice.get('discount_amount') or 0)
    if discount_amount > 0:
        discount_name = str(invoice.get('discount_name') or 'Discount').strip() or 'Discount'
        if str(invoice.get('discount_type') or 'fixed') == 'percent':
            lines.append(f"{discount_name} ({float(invoice.get('discount_value') or 0):,.2f}%): -Rs {discount_amount:,.2f}")
        else:
            lines.append(f"{discount_name}: -Rs {discount_amount:,.2f}")
    lines.extend([
        f"Grand Total: Rs {float(invoice.get('total_amount') or 0):,.2f}",
        '',
        'Thank you for your business.',
        'Generated by Malik Electronic inventory and billing system.',
    ])
    return lines


def _build_invoice_pdf_reportlab(output_path: str, invoice: dict, items: list[dict], shop_name: str) -> str:
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)

    c = canvas.Canvas(str(path), pagesize=A4)
    width, height = A4
    left = 16 * mm
    top = height - 18 * mm
    line_height = 6 * mm

    def start_page():
        c.setFont('Helvetica-Bold', 16)
        c.drawString(left, top, _sanitize(shop_name))
        c.setFont('Helvetica-Bold', 12)
        c.drawString(left, top - 8 * mm, 'Sales Invoice')
        c.setFont('Helvetica', 10)
        return top - 16 * mm

    y = start_page()
    for line in _invoice_lines(invoice, items, shop_name)[2:]:
        if y < 18 * mm:
            c.showPage()
            y = start_page()
        c.drawString(left, y, _sanitize(line))
        y -= line_height

    c.save()
    return str(path)


def _build_invoice_pdf_minimal(output_path: str, invoice: dict, items: list[dict], shop_name: str = 'Malik Electronic') -> str:
    lines = _invoice_lines(invoice, items, shop_name)
    text_ops = ['BT', '/F1 11 Tf', '15 TL', '48 794 Td']
    first = True
    for line in lines:
        if not first:
            text_ops.append('T*')
        text_ops.append(f"({_escape_pdf_text(line)}) Tj")
        first = False
    text_ops.append('ET')
    content_stream = '\n'.join(text_ops).encode('latin-1', 'replace')

    objects: list[bytes] = []
    objects.append(b'<< /Type /Catalog /Pages 2 0 R >>')
    objects.append(b'<< /Type /Pages /Kids [3 0 R] /Count 1 >>')
    objects.append(b'<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>')
    objects.append(b'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>')
    objects.append(f"<< /Length {len(content_stream)} >>\nstream\n".encode('latin-1') + content_stream + b'\nendstream')

    output = bytearray(b'%PDF-1.4\n%\xe2\xe3\xcf\xd3\n')
    xref_positions = [0]
    for idx, obj in enumerate(objects, start=1):
        xref_positions.append(len(output))
        output.extend(f'{idx} 0 obj\n'.encode('latin-1'))
        output.extend(obj)
        output.extend(b'\nendobj\n')

    xref_start = len(output)
    output.extend(f'xref\n0 {len(objects) + 1}\n'.encode('latin-1'))
    output.extend(b'0000000000 65535 f \n')
    for pos in xref_positions[1:]:
        output.extend(f'{pos:010d} 00000 n \n'.encode('latin-1'))
    output.extend(f'trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref_start}\n%%EOF'.encode('latin-1'))

    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(bytes(output))
    return str(path)


def build_invoice_pdf(output_path: str, invoice: dict, items: list[dict], shop_name: str = 'Malik Electronic') -> str:
    if REPORTLAB_AVAILABLE:
        return _build_invoice_pdf_reportlab(output_path, invoice, items, shop_name)
    return _build_invoice_pdf_minimal(output_path, invoice, items, shop_name)
